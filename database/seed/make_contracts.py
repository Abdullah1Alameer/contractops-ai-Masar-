"""Generate the two synthetic Arabic demo contracts (.docx) AND ground_truth.json.

We generate both from the same planted facts so eval.py grades against a single
source of truth. Hijri→Gregorian expectations are computed with hijri-converter
(the same library the backend uses).

    python database/seed/make_contracts.py
"""
import json
from pathlib import Path

from docx import Document
from hijri_converter import Hijri

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "database" / "demo_contracts"
OUT.mkdir(parents=True, exist_ok=True)


def h2g(y, m, d):
    from datetime import date
    return date(*Hijri(y, m, d).to_gregorian().datetuple()).isoformat()


def write_docx(path: Path, title: str, paragraphs: list[str]):
    doc = Document()
    doc.add_heading(title, level=1)
    for p in paragraphs:
        doc.add_paragraph(p)
    doc.save(path)


